function confirmCustomization() {

  const target = getCurrentCustomizationTarget();
  if (target) {
    target.specialInstructions =
      document.getElementById('special-instructions').value.trim();
  }

  if (pendingAddProductId) {

    const product =
      products.find(p => p.id === pendingAddProductId);

    if (product) {

      const qty =
        quantities[product.id] || 1;

      const existing =
        cart.find(c => c.id === product.id);

      const itemData =
        pendingCustomization || {
          size:'Medium',
          temp:'Hot',
          sugar:50
        };

      if (existing) {
        existing.qty += qty;
        existing.temp = itemData.temp;
        existing.sugar = itemData.sugar;
        existing.specialInstructions = itemData.specialInstructions;
      } else {
        cart.push({
          ...product,
          qty,
          ...itemData
        });
      }

      quantities[product.id] = 1;
      renderProducts();
      renderCart();
    }

    pendingAddProductId = null;
    pendingCustomization = null;
  }

  document
    .getElementById('customize-modal')
    .classList.add('hidden');

}


