function getVerseForProduct(id) {

  const product = products.find(
    p => p.id === id
  );

  if (!product) {
    return '';
  }

  return `“Taste and see that the Lord is good.” – Psalm 34:8`;
}


// ============================================================
// QUANTITY
// ============================================================

function changeQty(id, delta) {

  if (!quantities[id]) {
    quantities[id] = 1;
  }

  quantities[id] =
    Math.max(1, quantities[id] + delta);

  const el =
    document.getElementById(`qty-${id}`);

  if (el) {
    el.textContent = quantities[id];
  }
}


// ============================================================
// CART
// ============================================================

function addToCart(id) {

  const product =
    products.find(p => p.id === id);

  if (!product) {
    return;
  }

  if (!product.requiresCustomization) {
    const qty = quantities[id] || 1;
    const existing = cart.find(c => c.id === id);

    if (existing) {
      existing.qty += qty;
    } else {
      cart.push({
        ...product,
        qty
      });
    }

    quantities[id] = 1;
    renderProducts();
    renderCart();
    return;
  }

  pendingAddProductId = id;
  pendingCustomization = {
    size:'Medium',
    temp:'Hot',
      sugar:50
  };

  openModal(id, getVerseForProduct(id));
}


function removeFromCart(id) {

  cart =
    cart.filter(c => c.id !== id);

  renderProducts();

  renderCart();
}


function cartQty(id, delta) {

  const item =
    cart.find(c => c.id === id);

  if (item) {

    item.qty += delta;

    if (item.qty <= 0) {

      removeFromCart(id);

      return;
    }
  }

  renderCart();
}

function clearCart() {
  cart = [];
  renderProducts();
  renderCart();
}

function startOver() {
  if (cart.length > 0) {
    document.getElementById('start-over-modal').classList.remove('hidden');
    lucide.createIcons();
    return;
  }

  confirmStartOver();
}

function closeStartOverModal() {
  document.getElementById('start-over-modal').classList.add('hidden');
}

function confirmStartOver() {
  cart = [];
  quantities = {};
  currentEditItemId = null;
  pendingAddProductId = null;
  pendingCustomization = null;
  localStorage.removeItem('orderType');
  window.location.href = 'Opening.html';
}


